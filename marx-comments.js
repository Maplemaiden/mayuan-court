/**
 * 生成旁白
 * @param {'overview'|'detail'} mode
 * @param {number|null} pct 正确率 0–100，无数据为 null
 * @param {number} [q] 题号 1–6
 */
export function marxSay(mode, pct, q) {
  const tier = rateTier(pct);
  if (mode === 'overview') {
    return OVERVIEW[tier];
  }
  if (q === 6) {
    return PER_QUESTION[6][tier] || PER_QUESTION[6].empty;
  }
  const base = GENERIC[tier];
  const extra = PER_QUESTION[q] && PER_QUESTION[q][tier];
  if (tier === 'empty') return base;
  // 专属句优先展示，更贴题；通用句作兜底
  return extra || base;
}

export function tierName(pct) {
  return TIER_LABEL[rateTier(pct)];
}
